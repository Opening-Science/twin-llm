/**
 * bun scripts/gbd/build-location-map.ts <location_metadata.csv>
 *
 * Writes packages/gbd-local/location-table.ts: every GBD location id with its
 * parent, level, name, ISO 3166-1 alpha-3 code and, for the subnational sets
 * in iso-3166-2.ts, its ISO 3166-2 code.
 *
 * Input: IHME's public location metadata file
 * https://github.com/ihmeuw/CHAIN_IHME_adultmortality_edu_sysreview/blob/main/loction_metadata.csv
 * (columns location_name, location_id, ihme_loc_id, level, region_name,
 * super_region_name; rows in hierarchy sort order). For a country (level 3)
 * `ihme_loc_id` is its ISO 3166-1 alpha-3 code; for a subnational unit it is
 * the country code and the GBD id (`USA_523`). GBD's own hierarchy file for
 * GBD 2023 is on the GHDx behind a sign-in, so it is not used. The file
 * carries no parent id; a row's parent is the nearest row above it one level
 * up, and the script stops when that parent is not the same country.
 *
 * The table holds ids, names and codes only, no estimates.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { parseDelimited } from "../../packages/personal-data/delimited";

import { ISO_3166_2_BY_NAME } from "./iso-3166-2";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(ROOT, "packages", "gbd-local", "location-table.ts");
const SOURCE_URL =
  "https://github.com/ihmeuw/CHAIN_IHME_adultmortality_edu_sysreview/blob/main/loction_metadata.csv";

/** ISO 3166-1 gives these two GBD subnational units of China their own alpha-3 code. */
const OWN_ALPHA3: Readonly<Record<string, string>> = { "354": "HKG", "361": "MAC" };

export type BuiltLocation = Readonly<{
  id: number;
  parentId: number | null;
  level: number;
  name: string;
  iso3: string | null;
  iso31662: string | null;
}>;

const countryOf = (ihmeLocId: string): string | null =>
  /^[A-Z]{3}(_\d+)?$/.test(ihmeLocId) ? ihmeLocId.slice(0, 3) : null;

/** The table rows from the metadata text. Throws on a row it cannot place. */
export const buildLocations = (text: string): readonly BuiltLocation[] => {
  const parsed = parseDelimited(text.replace(/^﻿/, ""), ",");
  if (!parsed.ok) throw new Error(`unclosed quote on line ${parsed.line}`);
  const [header, ...rows] = parsed.rows;
  const at = (name: string): number => {
    const index = header?.indexOf(name) ?? -1;
    if (index === -1) throw new Error(`column ${name} missing`);
    return index;
  };
  const [nameAt, idAt, locAt, levelAt] = [
    at("location_name"),
    at("location_id"),
    at("ihme_loc_id"),
    at("level"),
  ];
  const lastAtLevel = new Map<number, Readonly<{ id: number; loc: string }>>();
  return rows.map((row) => {
    const id = Number(row[idAt]);
    const level = Number(row[levelAt]);
    const name = row[nameAt] ?? "";
    const loc = row[locAt] ?? "";
    if (!Number.isInteger(id) || !Number.isInteger(level)) {
      throw new Error(`bad id or level for ${name}`);
    }
    const parent = level === 0 ? null : (lastAtLevel.get(level - 1) ?? null);
    if (level > 0 && parent === null) throw new Error(`no parent for ${name}`);
    const country = level >= 3 ? countryOf(loc) : null;
    if (level >= 3 && country === null) throw new Error(`no country code for ${name}`);
    if (level >= 4 && countryOf(parent?.loc ?? "") !== country) {
      throw new Error(`${name} does not sit under its country`);
    }
    lastAtLevel.set(level, { id, loc });
    return {
      id,
      parentId: parent?.id ?? null,
      level,
      name,
      iso3: OWN_ALPHA3[String(id)] ?? country,
      iso31662:
        level >= 4 && country !== null
          ? (ISO_3166_2_BY_NAME[country]?.[name] ?? null)
          : null,
    };
  });
};

const render = (locations: readonly BuiltLocation[]): string =>
  [
    "/**",
    " * GBD location ids with parent, level, name, ISO 3166-1 alpha-3 and ISO",
    " * 3166-2 codes. Generated by scripts/gbd/build-location-map.ts; do not edit.",
    ` * Source: ${SOURCE_URL}`,
    " * (IHME location metadata; ISO 3166-2 checked by hand, scripts/gbd/iso-3166-2.ts).",
    " * Ids, names and codes only, no estimates.",
    " */",
    "export type GbdLocationEntry = readonly [",
    "  id: number,",
    "  parentId: number | null,",
    "  level: number,",
    "  name: string,",
    "  iso3: string | null,",
    "  iso3166_2: string | null,",
    "];",
    "",
    "export const GBD_LOCATION_TABLE: readonly GbdLocationEntry[] = [",
    ...locations.map(
      (location) =>
        `  ${JSON.stringify([
          location.id,
          location.parentId,
          location.level,
          location.name,
          location.iso3,
          location.iso31662,
        ])},`,
    ),
    "];",
    "",
  ].join("\n");

const isMain = Boolean((import.meta as { main?: boolean }).main);

if (isMain) {
  const path = process.argv[2];
  if (path === undefined) {
    console.error("usage: bun scripts/gbd/build-location-map.ts <location_metadata.csv>");
    process.exit(1);
  }
  const locations = buildLocations(readFileSync(path, "utf8"));
  writeFileSync(OUT, render(locations));
  const subnational = locations.filter((location) => location.level >= 4);
  console.log(
    `wrote ${OUT}: ${locations.length} locations, ${subnational.length} subnational, ${subnational.filter((location) => location.iso31662 !== null).length} with ISO 3166-2`,
  );
}
