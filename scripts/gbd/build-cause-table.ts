/**
 * bun scripts/gbd/build-cause-table.ts <cause.py>
 *
 * Writes packages/gbd-local/cause-table.ts: every GBD cause id with its
 * parent, level in the cause hierarchy and name (#409).
 *
 * Input: `cause.py` of IHME's public, BSD-3-Clause `vivarium-gbd-mapping`
 * package, built from the GBD 2023 cause hierarchy (its CHANGELOG, 5.0.0
 * "Update GBD Mapping for 2023"), at a pinned commit:
 * https://github.com/ihmeuw/vivarium-suite/blob/61376fb6da915e10c7bcc82e2145a2fbe6c2b0b9/libs/gbd-mapping/src/vivarium/gbd_mapping/cause.py
 * Each cause is a `Cause(name=..., gbd_id=c_id(N), ..., level=L, ...)` block;
 * parents are set at the end of the file (`causes.x.parent = causes.y`). The
 * names are the package's snake_case keys, not IHME's display names, so the
 * profile matches causes by id. GBD's own hierarchy file on the GHDx needs a
 * sign-in, so it is not used.
 *
 * The table holds ids, levels and names only, no estimates.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(ROOT, "packages", "gbd-local", "cause-table.ts");
export const CAUSE_SOURCE_URL =
  "https://github.com/ihmeuw/vivarium-suite/blob/61376fb6da915e10c7bcc82e2145a2fbe6c2b0b9/libs/gbd-mapping/src/vivarium/gbd_mapping/cause.py";

export type BuiltCause = Readonly<{
  id: number;
  parentId: number | null;
  level: number;
  name: string;
}>;

const CAUSE_BLOCK =
  /'(\w+)': Cause\(\s*name='(\w+)',\s*kind='cause',\s*gbd_id=c_id\((\d+)\),[\s\S]*?\blevel=(\d+),/g;
const PARENT_LINE = /^causes\.(\w+)\.parent = causes\.(\w+)$/gm;

/**
 * The table rows from the text of cause.py, sorted by id. Throws when a
 * parent is not a cause in the file or a level is not one below its
 * parent's, so a changed layout fails instead of writing a wrong table.
 */
export const buildCauses = (text: string): readonly BuiltCause[] => {
  const blocks = [...text.matchAll(CAUSE_BLOCK)].map((match) => ({
    key: match[1] ?? "",
    name: match[2] ?? "",
    id: Number(match[3]),
    level: Number(match[4]),
  }));
  if (blocks.length === 0) throw new Error("no causes found");
  const byKey = new Map(blocks.map((block) => [block.key, block] as const));
  if (byKey.size !== blocks.length) throw new Error("a cause key repeats");
  const parents = new Map(
    [...text.matchAll(PARENT_LINE)].map((match) => [match[1] ?? "", match[2] ?? ""]),
  );
  return blocks
    .map((block) => {
      if (block.key !== block.name)
        throw new Error(`${block.key} names itself ${block.name}`);
      const parentKey = parents.get(block.key);
      const parent = parentKey === undefined ? undefined : byKey.get(parentKey);
      if (parentKey !== undefined && parent === undefined) {
        throw new Error(`${block.key} has unknown parent ${parentKey}`);
      }
      if (parent === undefined && block.level !== 0) {
        throw new Error(`${block.key} at level ${block.level} has no parent`);
      }
      if (parent !== undefined && block.level !== parent.level + 1) {
        throw new Error(`${block.key} is not one level below ${parent.key}`);
      }
      return {
        id: block.id,
        parentId: parent?.id ?? null,
        level: block.level,
        name: block.name,
      };
    })
    .sort((a, b) => a.id - b.id);
};

const render = (causes: readonly BuiltCause[]): string =>
  [
    "/**",
    " * GBD 2023 cause ids with parent, level in the cause hierarchy (0 All",
    " * causes; 1 e.g. Non-communicable diseases; 2 e.g. Cardiovascular",
    " * diseases; 3; 4) and name. Generated by scripts/gbd/build-cause-table.ts;",
    " * do not edit.",
    ` * Source: ${CAUSE_SOURCE_URL}`,
    " * (IHME vivarium-gbd-mapping, BSD-3-Clause,",
    " * LICENSES/BSD-3-Clause-vivarium-gbd-mapping.txt; names are its snake_case keys).",
    " * Ids, levels and names only, no estimates.",
    " */",
    "export type GbdCauseEntry = readonly [",
    "  id: number,",
    "  parentId: number | null,",
    "  level: number,",
    "  name: string,",
    "];",
    "",
    "export const GBD_CAUSE_TABLE: readonly GbdCauseEntry[] = [",
    ...causes.map(
      (cause) =>
        `  ${JSON.stringify([cause.id, cause.parentId, cause.level, cause.name])},`,
    ),
    "];",
    "",
  ].join("\n");

const isMain = Boolean((import.meta as { main?: boolean }).main);

if (isMain) {
  const path = process.argv[2];
  if (path === undefined) {
    console.error("usage: bun scripts/gbd/build-cause-table.ts <cause.py>");
    process.exit(1);
  }
  const causes = buildCauses(readFileSync(path, "utf8"));
  writeFileSync(OUT, render(causes));
  const levels = [0, 1, 2, 3, 4].map(
    (level) =>
      `${causes.filter((cause) => cause.level === level).length} at level ${level}`,
  );
  console.log(`wrote ${OUT}: ${causes.length} causes, ${levels.join(", ")}`);
}
